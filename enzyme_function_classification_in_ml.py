"""# Cell 10 — Invalid Amino-Acid Character Inspection
Purpose: Inspect the sequence alphabet across the training dataset to determine which standard and non-standard/ambiguous amino-acid characters actually occur, and count how many sequences are affected by each.
"""

import pandas as pd
import numpy as np
from pathlib import Path

project_root = Path('/content/Enzyme-Function-Classification-Final')
raw_data_dir = project_root / 'data' / 'raw' / 'swissprot-ec'

def get_file_path(filename):
    p = raw_data_dir / filename
    if not p.exists():
        p = raw_data_dir / 'swissprot-ec' / filename
    return p

df_train = pd.read_parquet(get_file_path('train-00000-of-00001.parquet'))

# Identify sequence column dynamically
seq_col = [col for col in df_train.columns if 'seq' in col.lower() or 'protein' in col.lower()][0]

standard_aa = set("ACDEFGHIKLMNPQRSTVWY")
all_seen_chars = set()
non_standard_counts = {}

# Check all sequences in train set
for seq in df_train[seq_col].dropna():
    for char in seq:
        all_seen_chars.add(char)
        if char not in standard_aa:
            non_standard_counts[char] = non_standard_counts.get(char, 0) + 1

print(f"--- Amino-Acid Character Analysis ---")
print(f"All characters found in sequences: {sorted(list(all_seen_chars))}")
print(f"Standard amino acids found: {sorted([c for c in all_seen_chars if c in standard_aa])}")

non_standard_found = [c for c in all_seen_chars if c not in standard_aa]
print(f"Non-standard / ambiguous characters found: {sorted(non_standard_found)}")

if non_standard_found:
    print("\n--- Breakdown of Non-Standard Characters ---")
    ns_data = []
    total_seqs = len(df_train)
    for char in sorted(non_standard_found):
        # Count how many sequences contain this character
        count_seqs = df_train[seq_col].apply(lambda s: char in str(s)).sum()
        pct = (count_seqs / total_seqs) * 100
        ns_data.append({'Character': char, 'Affected Sequences': count_seqs, 'Percentage (%)': pct})

    ns_df = pd.DataFrame(ns_data)
    print(ns_df)
else:
    print("\nNo non-standard or ambiguous characters found in the training set sequences.")

