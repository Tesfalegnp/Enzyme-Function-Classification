"""#Cell 21 — Dipeptide Composition (400D) Feature Extraction
* Purpose: Compute the Dipeptide Composition (DPC) for every protein sequence, generating a 400-dimensional normalized feature vector (20×20 possible amino-acid pairs).
"""

import numpy as np
import pandas as pd
from pathlib import Path
from itertools import product

project_root = Path('/content/Enzyme-Function-Classification-Final')
processed_dir = project_root / 'data' / 'processed'

# Load splits
df_train = pd.read_parquet(processed_dir / 'train_split.parquet')
df_val = pd.read_parquet(processed_dir / 'val_split.parquet')
df_test = pd.read_parquet(processed_dir / 'test_split.parquet')

# Standard 20 amino acids
STANDARD_AA = sorted(list("ACDEFGHIKLMNPQRSTVWY"))
# Generate all 400 possible dipeptides
DIPEPTIDES = [f"{a}{b}" for a, b in product(STANDARD_AA, repeat=2)]
dpc_mapping = {dp: idx for idx, dp in enumerate(DIPEPTIDES)}

def compute_dpc(sequences):
    dpc_rows = []
    for seq in sequences:
        seq_str = str(seq)
        length = len(seq_str)
        counts = np.zeros(400, dtype=np.float32)

        if length > 1:
            total_pairs = length - 1
            for i in range(total_pairs):
                dp = seq_str[i:i+2]
                if dp in dpc_mapping:
                    counts[dpc_mapping[dp]] += 1.0
            # Normalize by total pairs
            if total_pairs > 0:
                counts /= total_pairs

        dpc_rows.append(counts)

    return np.array(dpc_rows, dtype=np.float32)

print("Computing Dipeptide Composition features for Train, Validation, and Test sets...")
X_train_dpc = compute_dpc(df_train['sequence'])
X_val_dpc = compute_dpc(df_val['sequence'])
X_test_dpc = compute_dpc(df_test['sequence'])

print(f"X_train_dpc shape: {X_train_dpc.shape}")
print(f"X_val_dpc shape:   {X_val_dpc.shape}")
print(f"X_test_dpc shape:  {X_test_dpc.shape}")

