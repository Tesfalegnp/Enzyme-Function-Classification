# Standard 20 amino acids alphabetical order
STANDARD_AA = sorted(list("ACDEFGHIKLMNPQRSTVWY"))

def compute_aac(sequences):
    aac_rows = []
    for seq in sequences:
        seq_str = str(seq)
        length = len(seq_str)
        counts = {aa: 0.0 for aa in STANDARD_AA}

        if length > 0:
            for char in seq_str:
                if char in counts:
                    counts[char] += 1.0
            # Normalize by sequence length to get frequencies
            for aa in counts:
                counts[aa] /= length

        aac_rows.append([counts[aa] for aa in STANDARD_AA])

    return np.array(aac_rows, dtype=np.float32)

