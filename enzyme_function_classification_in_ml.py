"""# **PHASE 4 — FEATURE ENGINEERING**

# Cell 20 — Amino Acid Composition (AAC - 20D) Feature Extraction
* Purpose: Compute the Amino Acid Composition (AAC) for every protein sequence, generating a 20-dimensional normalized frequency vector representing the proportion of each standard amino acid.
"""

import numpy as np
import pandas as pd
from pathlib import Path

project_root = Path('/content/Enzyme-Function-Classification-Final')
