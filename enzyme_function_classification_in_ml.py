    # Function to extract first digit depending on structure (string vs list)
    def extract_first_digit(val):
        if val is None:
            return None
        # If it's a list or array-like
        if isinstance(val, (list, np.ndarray, pd.Series)):
            first_val = str(val[0])
        else:
            first_val = str(val)

        # Clean string to get first digit (e.g. 'EC:1.1.1.1' -> '1' or '1.1.1.1' -> '1')
        clean_val = first_val.replace('EC:', '').strip()
        if len(clean_val) > 0 and clean_val[0].isdigit():
            return int(clean_val[0])
        return None

    # Apply across train set
    train_first_digits = df_train[label_col].apply(extract_first_digit)

    print("\n--- Observed EC First-Digit Distribution (Train Set, Pre-Filtering) ---")
    dist = train_first_digits.value_counts().sort_index()
    dist_df = pd.DataFrame({
        'Count': dist,
        'Percentage (%)': (dist / len(train_first_digits)) * 100
    })
